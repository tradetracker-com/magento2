declare(strict_types=1);

namespace TradeTracker\Connect\Test\Unit\Architecture;

use PHPUnit\Framework\TestCase;

/**
 * E2E-TESTS.md is generated (Test/End-2-end/scripts/e2e-tests-md.mjs) and committed. This keeps it
 * current without Node in the CI PHPUnit job: every spec file has a section and every literal test
 * title appears, so a new or renamed test without a regenerated document fails the build.
 * Hand-maintained copies drifted (alternatehreflang claimed 191 tests and had 180).
 */
class E2eDocsCurrentTest extends TestCase
{
    public function testEverySpecAndEveryLiteralTestTitleIsDocumented(): void
    {
        $root = dirname(__DIR__, 3);
        $doc = (string)file_get_contents($root . '/E2E-TESTS.md');
        $this->assertStringContainsString('Generated by', $doc, 'E2E-TESTS.md must be the generated document');
        $this->assertFileDoesNotExist($root . '/Test/End-2-end/E2E-TESTS.md', 'no second copy of E2E-TESTS.md');

        $missing = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/Test/End-2-end/tests', \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            /** @var \SplFileInfo $file */
            if (!str_ends_with($file->getFilename(), '.spec.ts')) {
                continue;
            }
            $relative = substr($file->getPathname(), strlen($root . '/Test/End-2-end/tests/'));
            if (!str_contains($doc, '(`' . $relative . '`)')) {
                $missing[] = $relative . ' (no section)';
            }
            $source = (string)file_get_contents($file->getPathname());
            preg_match_all("/^\\s*test\\('([^'\\\\]*)'/m", $source, $m);
            foreach ($m[1] as $title) {
                if (!str_contains($doc, $title)) {
                    $missing[] = $relative . ': ' . $title;
                }
            }
        }
        $this->assertSame([], $missing, 'regenerate: cd Test/End-2-end && node scripts/e2e-tests-md.mjs > ../../E2E-TESTS.md');
    }
}
