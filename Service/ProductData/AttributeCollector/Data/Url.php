declare(strict_types=1);

namespace TradeTracker\Connect\Service\ProductData\AttributeCollector\Data;

use Magento\Framework\UrlInterface;
use Magento\Store\Api\Data\StoreInterface;
use Magento\Store\Model\Store;

/**
 * Service class for URL data
 * Allow to get URLs for categories, pages and products
 */
class Url extends AbstractDataCollector
{

    /**
     * URL pattern for entities
     */
    public const URL_PATTERN = '%s%s';

    /**
     * URL patterns for no-rewrite items
     */
    public const URL_PATTERN_EXTRA = [
        'product' => '%scatalog/product/view/id/%s',
        'cms-page' => '%scms/page/view/page_id/%s',
        'category' => '%scatalog/category/view/id/%s'
    ];

    private array $entityIds;
    private array $productIds;
    private string $type;
    private StoreInterface $store;

    public function execute(array $entityIds, string $type, StoreInterface $store, ?array $productIds = null): array
    {
        $this->entityIds = $entityIds;
        $this->store = $store;
        $this->productIds = $productIds ?? [];
        $this->type = $type;

        return $this->collectUrl();
    }

    /**
     * Collect URL data for entities
     *
     * @return array
     */
    private function collectUrl(): array
    {
        $result = [];
        $select = $this->resource->getConnection()
            ->select()->from(
                ['catalog_product_entity' => $this->resource->getTableName('catalog_product_entity')],
                ['entity_id', $this->linkField]
            )
            ->join(
                ['url_rewrite' => $this->resource->getTableName('url_rewrite')],
                'catalog_product_entity.entity_id = url_rewrite.entity_id',
            )
            ->where("catalog_product_entity.{$this->linkField} in (?)", $this->entityIds)
            ->where('url_rewrite.redirect_type = ?', 0)
            ->where('url_rewrite.is_autogenerated = ?', 1)
            ->where('url_rewrite.metadata IS NULL OR url_rewrite.metadata = ?', '[]')
            ->where('url_rewrite.store_id = ?', (int)$this->store->getId())
            ->where('url_rewrite.entity_type = ?', $this->type);

        $values = $this->resource->getConnection()->fetchAll($select);

        // URL_TYPE_WEB for the domain: it reads web/unsecure/base_url of this store directly,
        // where URL_TYPE_LINK goes through the base_link_url placeholder (multi-domain
        // stores). But only URL_TYPE_LINK appends the store code, so with "Add Store Code to Urls"
        // every link of a non-default store view opened the default store. The code is added here
        // the way Magento's own _updatePathUseStoreView() does it.
        $storeUrl = $this->store->getBaseUrl(UrlInterface::URL_TYPE_WEB);
        if ($this->store instanceof Store && $this->store->isUseStoreInUrl()) {
            $storeUrl .= $this->store->getCode() . '/';
        }
        foreach ($values as $value) {
            $entityId = $value['entity_id'] ?? null;
            if ($entityId === null) {
                continue;
            }
            $result[$entityId] = sprintf(
                self::URL_PATTERN,
                $storeUrl,
                $value['request_path']
            );
        }

        if ($this->type === 'product') {
            foreach ($this->productIds as $productId) {
                if (!array_key_exists($productId, $result)) {
                    $result[$productId] = sprintf(
                        self::URL_PATTERN_EXTRA[$this->type],
                        $storeUrl,
                        $productId
                    );
                }
            }
        } else {
            foreach ($this->entityIds as $entityId) {
                if (!array_key_exists($entityId, $result)) {
                    $result[$entityId] = sprintf(
                        self::URL_PATTERN_EXTRA[$this->type],
                        $storeUrl,
                        $entityId
                    );
                }
            }
        }

        return $result;
    }
}
